class StrongLSTMClassifier(nn.Module):
    def __init__(self,vocab_size, embedding_dim=300, hidden_dim=192, num_layers=2, bidirectional=True, dropout=0.55, embed_dropout=0.25, output_dim=1,):
        super().__init__()
        self.bidirectional = bidirectional

        self.embedding = nn.Embedding(
            vocab_size,
            embedding_dim,
            padding_idx=vocab["<unk>"],
        )
        self.embed_norm = nn.LayerNorm(embedding_dim)
        self.embedding_dropout = nn.Dropout(embed_dropout)
        self.lstm = nn.LSTM(
            input_size=embedding_dim,
            hidden_size=hidden_dim,
            num_layers=num_layers,
            batch_first=True,
            bidirectional=bidirectional,
            dropout=dropout if num_layers > 1 else 0.0,
        )
        factor = 2 if bidirectional else 1
        fc_dim = hidden_dim * factor * 2
        self.lstm_norm = nn.LayerNorm(hidden_dim * factor)
        self.dropout = nn.Dropout(dropout)
        self.fc = nn.Linear(fc_dim, output_dim)
        self.sigmoid = nn.Sigmoid()
    def forward(self, x):
        embedded = self.embedding(x)
        embedded = self.embed_norm(embedded)
        embedded = self.embedding_dropout(embedded)
        output, (hidden, _) = self.lstm(embedded)
        if self.bidirectional:
            h_forward = hidden[-2]
            h_backward = hidden[-1]
            h_cat = torch.cat((h_forward, h_backward), dim=1)
        else:
            h_cat = hidden[-1]
        pooled = torch.max(output, dim=1).values
        h_cat = self.lstm_norm(h_cat)
        h_final = torch.cat([h_cat, pooled], dim=1)
        h_final = self.dropout(h_final)
        logits = self.fc(h_final)
        probs = self.sigmoid(logits)
        return probs

