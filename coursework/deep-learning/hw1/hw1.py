class LogisticRegression(torch.nn.Module):
  def __init__(self, input_dim, output_dim):
    super().__init__()
    self.linear = torch.nn.Linear(input_dim, output_dim)
  def forward(self, x):
    return self.linear(x)

epochs = 10000
input_dim = 784
output_dim = 10
lr=0.01
model = LogisticRegression(input_dim, output_dim)
model=model.to(device)
criterion = torch.nn.CrossEntropyLoss()
optimizer = torch.optim.SGD(model.parameters(),lr=lr)

epochs = 10000

loss_save_arr_train = []
loss_save_arr_test  = []
for i in range(epochs):
    model.train()
    optimizer.zero_grad()
    output = model(X_train)
    loss = criterion(output, y_train.long())
    loss.backward()
    optimizer.step()
    if (i+1) % 10 == 0:
        model.eval()
        with torch.no_grad():
            test_output = model(X_test)
            test_loss = criterion(test_output, y_test.long())
        loss_save_arr_train.append(loss.item())
        loss_save_arr_test.append(test_loss.item())
    if (i+1) % 1000 == 0:
        print('epoch', i+1)
        _, pred = torch.max(output.data, axis=1)
        train_acc = float((pred == y_train).sum()) / y_train.size(0)
        print("train_accuracy {:0.3f}".format(train_acc))
        model.eval()
        with torch.no_grad():
            output = model(X_test)
            _, pred = torch.max(output.data, axis=1)
            test_acc = float((pred == y_test).sum()) / y_test.size(0)
            print("Test_accuracy {:0.3f}".format(test_acc))

plt.plot(loss_save_arr_train, label='Train Loss')
plt.plot(loss_save_arr_test, label='Test Loss')
plt.xlabel('Record Step (every 10 epochs)')
plt.ylabel('Loss')
plt.legend()
plt.show()