# ===== 학습 (Adagrad + 얼리 스톱 옵션) =====
torch.manual_seed(seed)
model = MLP_BN().to(device)
criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.Adagrad(model.parameters())  # lr=0.01 (default)

train_losses, val_losses, val_accs = [], [], []
best_val = float("inf")
best_state = None
patience, wait = 5, 0

print(f"== Train BN, Adagrad, bs={batch_size_final}, epochs={epochs} ==")
for epoch in range(epochs):
    # train
    model.train()
    loss_sum, cnt = 0.0, 0
    for x, y in norm_train_loader:
        x, y = x.to(device), y.to(device)
        optimizer.zero_grad()
        logits = model(x)
        loss = criterion(logits, y)
        loss.backward()
        optimizer.step()
        loss_sum += loss.item() * y.size(0)
        cnt     += y.size(0)
    train_losses.append(loss_sum / cnt)

    # val
    model.eval()
    vloss_sum, vcnt, vcorrect = 0.0, 0, 0
    with torch.no_grad():
        for x, y in norm_val_loader:
            x, y = x.to(device), y.to(device)
            out = model(x)
            vloss_sum += criterion(out, y).item() * y.size(0)
            vcnt      += y.size(0)
            vcorrect  += (out.argmax(1) == y).sum().item()
    val_loss = vloss_sum / vcnt
    val_acc  = vcorrect / vcnt
    val_losses.append(val_loss)
    val_accs.append(val_acc)

    # 로그
    print(f"[Epoch {epoch:02d}] train_loss={train_losses[-1]:.4f} | val_loss={val_loss:.4f} | val_acc={val_acc*100:5.2f}%")

    # Early Stopping(선택)
    if val_loss < best_val:
        best_val = val_loss
        best_state = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
        wait = 0
    else:
        wait += 1
        if wait >= patience:
            print(f"Early stopping at epoch {epoch} (no improvement for {patience} epochs).")
            break

