class MLP(nn.Module):
    def __init__(self):
        super().__init__()
        self.fc1 = nn.Linear(2, 2)
        self.fc2 = nn.Linear(2, 2)
    def forward(self, x):
        h = torch.tanh(self.fc1(x))
        return self.fc2(h)

model = MLP().to(device)
criterion = nn.CrossEntropyLoss()
optimizer = torch.optim.Adam(model.parameters(), lr=1e-2)

epochs = 1000
for ep in range(epochs):
    model.train()
    optimizer.zero_grad()
    logits = model(X_train)
    loss = criterion(logits, y_train)
    loss.backward()
    optimizer.step()

    if (ep+1) % 100 == 0:
        with torch.no_grad():
            tr_acc = (torch.argmax(logits, 1) == y_train).float().mean().item()
        print(f"Epoch [{ep+1}/{epochs}]  loss={loss.item():.4f}  train_acc={tr_acc:.3f}")

model.eval()
with torch.no_grad():
    train_pred = torch.argmax(model(X_train), dim=1)
    test_pred  = torch.argmax(model(X_test),  dim=1)
    train_acc = (train_pred == y_train).float().mean().item()
    test_acc  = (test_pred  == y_test ).float().mean().item()

print(f"\nMLP - Train Accuracy: {train_acc:.3f}")
print(f"MLP - Test  Accuracy: {test_acc:.3f}")

def plot_mlp_decision_line(model, train, test, X_train, X_test, title="MLP Decision Boundary"):
    model.eval()

    # 전체 데이터의 x, y 범위 계산
    all_xy = np.vstack([train[:, :2], test[:, :2]])
    x_min, x_max = all_xy[:,0].min() - 1, all_xy[:,0].max() + 1
    y_min, y_max = all_xy[:,1].min() - 1, all_xy[:,1].max() + 1

    # 격자(grid) 생성
    xx, yy = np.meshgrid(
        np.linspace(x_min, x_max, 300),
        np.linspace(y_min, y_max, 300)
    )
    grid = np.c_[xx.ravel(), yy.ravel()]
    grid_tensor = torch.tensor(grid, dtype=torch.float32).to(next(model.parameters()).device)

    # 모델 예측값 계산
    with torch.no_grad():
        pred = torch.argmax(model(grid_tensor), dim=1).cpu().numpy()
    Z = pred.reshape(xx.shape)

    # 시각화 (선만)
    plt.figure(figsize=(7,6))
    plt.contour(xx, yy, Z, levels=[0.5], colors='k', linewidths=2)  # 경계선만

    # 데이터 포인트
    plt.scatter(train[train[:,2]==0][:,0], train[train[:,2]==0][:,1], color='blue', marker='o', label='Train 0')
    plt.scatter(train[train[:,2]==1][:,0], train[train[:,2]==1][:,1], color='red',  marker='o', label='Train 1')
    plt.scatter(test[test[:,2]==0][:,0],  test[test[:,2]==0][:,1],  color='blue', marker='x', label='Test 0')
    plt.scatter(test[test[:,2]==1][:,0],  test[test[:,2]==1][:,1],  color='red',  marker='x', label='Test 1')

    plt.xlim(x_min, x_max)
    plt.ylim(y_min, y_max)
    plt.title(title)
    plt.xlabel("x1")
    plt.ylabel("x2")
    plt.legend()
    plt.grid(True)
    plt.show()
plot_mlp_decision_line(model, train, test, X_train, X_test, title="MLP Decision Boundary")